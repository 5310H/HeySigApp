package com.heysig.noise

fun main() {
    check(!EnvironmentReleaseGate.qualified())
    val id="12345678-1234-1234-1234-123456789abc"
    val link=WatchEnvironmentSession(id,1000).receive(id,0,100,2000)
    check(runCatching { link.receive(id,0,0,3000) }.isFailure)
    check(runCatching { link.receive(id,1,5001,3000) }.isFailure)
    check(runCatching { link.receive("old-session",1,0,3000) }.isFailure)
    check(runCatching { link.copy(connected=false).receive(id,1,0,3000) }.isFailure)
    check(link.expired(75_001,SamplingSchedule()))
    check(!link.expired(75_000,SamplingSchedule()))
    check(WatchEnvironmentSession(id,80_000).receive(id,0,0,81_000).sequence==0L)
    val access=EnvironmentCaptureAccess(true,true,true,true)
    check(access.blocked()==null)
    check(access.copy(foreground=false).blocked()!=null)
    check(access.copy(unlocked=false).blocked()!=null)
    check(access.copy(permissionGranted=false).blocked()!=null)
    check(access.copy(microphoneAvailable=false).blocked()!=null)
    check(environmentSampleAfterPlayback(10_000,3,0,null))
    check(!environmentSampleAfterPlayback(10_000,3,0,6000))
    check(!environmentSampleAfterPlayback(11_000,3,0,6000))
    check(environmentSampleAfterPlayback(11_001,3,0,6000))
    check(!environmentSampleAfterPlayback(16_000,3,5000,6000))
    check(environmentSampleAfterPlayback(16_001,3,5000,6000))
    val available=(1..6).map { EnvironmentProgram(it,"My program $it") }.toSet()
    val settings=EnvironmentSettings(available.toList(),enabled=true)
    val restaurant=EnvironmentClassification(ListeningEnvironment.RESTAURANT,0.9,"fixture")
    fun sample(state: EnvironmentState, time: Long, result: EnvironmentClassification=restaurant,
               config: EnvironmentSettings=settings, current: Int?=1, safe: Boolean=true,
               programs: Set<EnvironmentProgram> = available, sleep: Set<Int> = emptySet()) =
        EnvironmentSwitching.sample(state,result,time,config,programs,current,safe,sleep)
    val initial=EnvironmentSwitching.start(EnvironmentState(),1000)
    val first=sample(initial,2000)
    check(first.target==null && first.state.phase==SwitchingPhase.STABILITY_WAIT)
    check(sample(first.state,16_999).target==null)
    val stable=sample(first.state,17_000)
    check(stable.target?.slot==4)
    check(sample(stable.state,18_000).target==null) // no concurrent command
    check(EnvironmentSwitching.complete(stable.state,stable.state.token+1,true,18_000,settings)==stable.state)
    val complete=EnvironmentSwitching.complete(stable.state,stable.state.token,true,18_000,settings)
    check(complete.cooldownUntil==138_000L)
    check(complete.remainingSeconds(18_001)==120L)
    val cooldown=sample(complete,20_000)
    check(cooldown.state.phase==SwitchingPhase.COOLDOWN && cooldown.state.candidate==ListeningEnvironment.RESTAURANT)
    val ongoing=sample(cooldown.state,70_000)
    val ongoing2=sample(ongoing.state,120_000)
    check(sample(ongoing2.state,137_999).target==null)
    check(sample(ongoing2.state,138_000).target?.slot==4)
    check(sample(first.state,18_000,current=4).target==null) // duplicate
    check(sample(first.state,18_000,programs=available-available.elementAt(3)).state.phase==SwitchingPhase.ERROR)
    check(sample(first.state,18_000,programs=available.map { it.copy(name="Renamed") }.toSet()).target==null)
    check(sample(first.state,18_000,safe=false).target==null) // permission/background/audio priority
    check(sample(first.state,18_000,current=null).target==null)
    check(sample(first.state,18_000,sleep=setOf(1)).target==null)
    check(sample(first.state,18_000,sleep=setOf(4)).target==null)
    check(sample(first.state,18_000,result=restaurant.copy(confidence=0.2)).state.candidate==null)
    check(sample(first.state,18_000,result=restaurant.copy(environment=null)).target==null)
    check(sample(first.state,18_000,config=settings.copy(assignments=List(6) { null })).target==null)
    check(sample(first.state,18_000,config=settings.copy(enabled=false)).target==null)
    check(sample(first.state,100_000).target==null) // missing samples reset stability
    val failure=EnvironmentSwitching.complete(stable.state,stable.state.token,false,18_000,settings)
    check(!failure.monitoring && failure.cooldownUntil==0L && failure.phase==SwitchingPhase.ERROR)
    val manual=EnvironmentSwitching.manual(complete,30_000,settings)
    check(manual.cooldownUntil==150_000L && manual.overrideUntil==150_000L)
    check(sample(manual,31_000).state.phase==SwitchingPhase.MANUAL_OVERRIDE)
    val noRestart=EnvironmentSwitching.manual(complete,30_000,settings.copy(restartAfterManual=false))
    check(noRestart.cooldownUntil==complete.cooldownUntil)
    val zero=settings.copy(cooldownSeconds=0,overrideSeconds=0)
    check(EnvironmentSwitching.complete(stable.state,stable.state.token,true,18_000,zero).cooldownUntil==18_000L)
    check(EnvironmentSwitching.complete(stable.state,stable.state.token,true,18_000,zero).phase==SwitchingPhase.MONITORING)
    check(sample(first.state.copy(cooldownUntil=999_999),17_000,config=zero).target?.slot==4)
    check(!sample(initial,1_801_000).state.monitoring) // default timeout
    check(!sample(EnvironmentSwitching.stop(first.state),18_000).state.monitoring)
    // A fresh reconnection starts evidence again, never replays a classification or pending target.
    check(sample(EnvironmentSwitching.start(EnvironmentSwitching.stop(first.state),20_000),21_000).target==null)
    check(sample(first.state,2000).state.phase==SwitchingPhase.ERROR)

    val unusual=settings.copy(assignments=listOf(EnvironmentProgram(1,"Custom : Ω\nname"),null,null,null,null,null))
    check(EnvironmentSettingsCodec.decode(EnvironmentSettingsCodec.encode(unusual))==unusual)
    check(EnvironmentSettingsCodec.decode(EnvironmentSettingsCodec.encode(settings))==settings)
    check(runCatching { EnvironmentSettingsCodec.decode("1:9") }.isFailure)
    check(runCatching { EnvironmentSettingsCodec.decode(EnvironmentSettingsCodec.encode(settings)+"x") }.isFailure)
    check(runCatching { settings.copy(cooldownSeconds=601) }.isFailure)
    check(runCatching { SamplingSchedule(10,3,30) }.isFailure)
    for(interval in listOf(15,30,60)) for(duration in listOf(3,5,10)) {
        val schedule=SamplingSchedule(interval,duration,15)
        check(duration<interval && !schedule.expired(1000,900_999) && schedule.expired(1000,901_000))
    }
    check(!SamplingSchedule(timeoutMinutes=0).expired(1000,Long.MAX_VALUE))

    fun classify(vararg scores: Pair<String,Double>)=EnvironmentClassifier.classify(List(5) { scores.toMap() })
    check(classify("Silence" to 0.95).environment==ListeningEnvironment.QUIET)
    check(classify("Speech" to 0.9).environment==ListeningEnvironment.CONVERSATION)
    check(classify("Conversation" to 0.9,"Hubbub, speech noise, speech babble" to 0.6).environment==ListeningEnvironment.SMALL_GROUP)
    check(classify("Speech" to 0.9,"Hubbub, speech noise, speech babble" to 0.8,"Dishes, pots, and pans" to 0.7).environment==ListeningEnvironment.RESTAURANT)
    check(classify("Crowd" to 0.9,"Hubbub, speech noise, speech babble" to 0.8).environment==ListeningEnvironment.LARGE_GROUP)
    check(classify("Traffic noise, roadway noise" to 0.9).environment==ListeningEnvironment.NON_SPEECH_NOISE)
    check(classify("Music" to 0.95).environment==null)
    check(classify("Speech" to 0.45).environment==null)
    check(classify("Speech" to Double.NaN).environment==null)
    check(EnvironmentClassifier.classify(emptyList()).environment==null)
    for(environment in ListeningEnvironment.entries) {
        val phrase=if(environment==ListeningEnvironment.NON_SPEECH_NOISE) "noise mode" else "${environment.label} mode"
        check(EnvironmentVoice.parse(phrase)==EnvironmentCommand.Select(environment))
    }
    check(EnvironmentVoice.parse("Automatic on")==EnvironmentCommand.Automatic(true))
    check(EnvironmentVoice.parse("automatic off")==EnvironmentCommand.Automatic(false))
    check(EnvironmentVoice.parse("Cooldown two minutes")==EnvironmentCommand.Cooldown(120))
    check(EnvironmentVoice.parse("Cooldown five minutes")==EnvironmentCommand.Cooldown(300))
    check(EnvironmentVoice.parse("Cooldown 11 minutes")==null)
    check(EnvironmentVoice.parse("don't turn automatic on")==null)
    check(EnvironmentVoice.parse("restaurant mode and quiet mode")==null)
    check(EnvironmentVoice.parse("start monitoring")==EnvironmentCommand.Monitor(true))
    check(EnvironmentVoice.parse("stop monitoring")==EnvironmentCommand.Monitor(false))
    check(EnvironmentVoice.parse("What's my status?")==EnvironmentCommand.Status)
    println("PASS: semantic assignments/persistence, six score mappings/abstention, stable decisions, cooldown, manual priority, sleep, failure, session expiry and voice grammar")
}
