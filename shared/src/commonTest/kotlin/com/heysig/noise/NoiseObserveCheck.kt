package com.heysig.noise

fun main() {
    val settings = NoiseSettings(programs=listOf(1,1,null,3,6,2))
    settings.validate((1..6).toSet())
    fun invalid(next:NoiseSettings) = check(runCatching { next.validate((1..6).toSet()) }.isFailure)
    invalid(settings.copy(boundaries=listOf(-60.0,-50.0,-50.0,-30.0,-20.0)))
    invalid(settings.copy(boundaries=listOf(-60.0,-56.0,-40.0,-30.0,-20.0)))
    invalid(settings.copy(boundaries=listOf(Double.NaN,-50.0,-40.0,-30.0,-20.0)))
    invalid(settings.copy(programs=listOf(1,2)))
    invalid(settings.copy(programs=listOf(1,2,3,4,5,7)))
    invalid(settings.copy(freshnessSeconds=15))
    invalid(settings.copy(confirmations=0))
    invalid(settings.copy(captureSeconds=11))
    invalid(settings.copy(margin=Double.POSITIVE_INFINITY))
    val first = observeNoise(NoiseObservation(),-60.0,1000,settings)
    check(first.level == 1 && first.count == 1 && first.proposed == null)
    val edge = observeNoise(first,-58.0,2000,settings)
    check(edge.level == 1 && edge.count == 2)
    val louderSameProgram = observeNoise(edge,-57.9,3000,settings)
    check(louderSameProgram.level == 2 && louderSameProgram.count == 3 && louderSameProgram.proposed == 1)
    val hold = observeNoise(louderSameProgram,-62.0,4000,settings)
    check(hold.level == 2)
    check(observeNoise(hold,-62.1,5000,settings).level == 1)
    val unused = observeNoise(louderSameProgram,-45.0,4000,settings)
    check(unused.level == 3 && unused.target == null && unused.count == 0 && unused.proposed == null)
    val jump = observeNoise(first,-10.0,2000,settings)
    check(jump.level == 6 && jump.target == 2 && jump.count == 1)
    check(observeNoise(jump,-90.0,3000,settings).level == 1)
    val stale = observeNoise(louderSameProgram,-57.9,50000,settings)
    check(stale.level == 2 && stale.count == 1 && stale.proposed == null)
    check(observeNoise(louderSameProgram,-57.9,500,settings).count == 1)
    check(runCatching { observeNoise(first,Double.NaN,5000,settings) }.isFailure)
    check(NoiseVoice.parse("Assign program three to noise level five") == NoiseCommand.Assign(5,3))
    check(NoiseVoice.parse("leave noise level four unused") == NoiseCommand.Assign(4,null))
    check(NoiseVoice.parse("assign program seven to noise level five") == null)
    check(NoiseVoice.parse("assign program three to noise level 5.5") == null)
    check(NoiseVoice.parse("set noise threshold one to minus fifty five point five") == NoiseCommand.SetField("threshold 1",-55.5))
    check(NoiseVoice.parse("set noise threshold five to -20") == NoiseCommand.SetField("threshold 5",-20.0))
    check(NoiseVoice.parse("set noise threshold six to minus twenty") == null)
    check(NoiseVoice.parse("volume five") == null)
    check(NoiseVoice.parse("set noise margin to minus negative two") == null)
    println("PASS: six-level validation, edge equality, hysteresis, repeated/unused targets, jumps, stale gaps and voice settings")
}
