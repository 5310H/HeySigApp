package com.heysig.noise

fun main() {
    fun frame(vararg values: Pair<String,Double>)=EnvironmentClassifier.requiredLabels.associateWith { 0.0 }+values.toMap()
    fun classify(vararg values: Pair<String,Double>)=SoundTypeClassifier.classify(List(5) { frame(*values) })
    check(classify("Speech" to .8)==SoundType.SPEECH)
    check(classify("Speech" to .8,"Engine" to .5)==SoundType.MIXED)
    check(classify("Speech" to .8,"Hubbub, speech noise, speech babble" to .5)==SoundType.MIXED)
    check(classify("Mechanical fan" to .8)==SoundType.NOISE)
    check(classify("Speech" to .8,"Engine" to .25)==SoundType.UNKNOWN)
    check(classify("Speech" to .8,"Music" to .2)==SoundType.UNKNOWN)
    check(classify("Music" to .9)==SoundType.UNKNOWN)
    check(classify("Silence" to .9)==SoundType.UNKNOWN)
    check(classify("Speech" to .59)==SoundType.UNKNOWN)
    check(classify()==SoundType.UNKNOWN)
    check(SoundTypeClassifier.classify(List(5) { mapOf("Speech" to .9) })==SoundType.UNKNOWN)
    check(classify("Speech" to Double.NaN)==SoundType.UNKNOWN)
    check(classify("Speech" to 1.01)==SoundType.UNKNOWN)
    check(SoundTypeClassifier.classify(List(2) { frame("Speech" to .8) })==SoundType.UNKNOWN)
    check(SoundTypeClassifier.classify(List(33) { frame("Speech" to .8) })==SoundType.UNKNOWN)
    val speech=frame("Speech" to .8)
    val noise=frame("Engine" to .8)
    check(SoundTypeClassifier.classify(listOf(speech,speech,speech,speech,noise))==SoundType.SPEECH)
    check(SoundTypeClassifier.classify(listOf(speech,speech,speech,noise,noise))==SoundType.UNKNOWN)
    check(SoundTypeClassifier.classify(listOf(speech,noise,speech,noise,speech,noise))==SoundType.UNKNOWN)
    var observation=SoundTypeObservation().next(SoundType.SPEECH,1000,1200)
    check(observation.count==1 && observation.shown==SoundType.UNKNOWN)
    observation=observation.next(SoundType.SPEECH,11000,11200)
    check(observation.shown==SoundType.SPEECH)
    check(observation.next(SoundType.MIXED,21000,21200).shown==SoundType.UNKNOWN)
    check(observation.next(SoundType.UNKNOWN,21000,21200)==SoundTypeObservation())
    check(observation.next(SoundType.SPEECH,40000,40200).count==1)
    check(observation.next(SoundType.SPEECH,11000,11200).count==1) // duplicate cannot confirm
    check(observation.next(SoundType.SPEECH,21000,32000)==SoundTypeObservation())
    check(observation.next(SoundType.SPEECH,21000,20000)==SoundTypeObservation())
    check(!EnvironmentReleaseGate.qualified())
    println("PASS: display-only speech/noise/mixed evidence, ambiguous/music/quiet rejection, frame agreement, two fresh captures and stale/reset behavior; not accuracy acceptance")
}
