package com.heysig.sleep

import com.heysig.control.*
import java.time.*

fun main() {
    val fitting=Fitting(12,12,12,listOf(Program(1,"Universal",TinnitusCapability.SUPPORTED),Program(2,"Sleep",TinnitusCapability.UNKNOWN),Program(5,"TV!",TinnitusCapability.UNKNOWN)))
    val valid=SleepRoutine(1320,420,2,1)
    valid.validate(fitting)
    for(value in listOf(SleepRoutine(),valid.copy(wakeMinute=1320),valid.copy(sleepMinute=-1),valid.copy(wakeMinute=1440),valid.copy(wakeSlot=6)))
        check(runCatching { value.validate(fitting) }.isFailure)
    for((input,minute) in listOf("ten pm" to 1320,"seven am" to 420,"12 am" to 0,"12 pm" to 720,"7:35 pm" to 1175,"22:00" to 1320,"00:00" to 0,"noon" to 720,"midnight" to 0))
        check(SleepVoice.time(input)==minute) { input }
    for(input in listOf("ten","7","7 or 8 pm","25:00","24:00","10:60 pm","0 pm","13 pm","7.5 pm","-1:00","07:00 tomorrow")) check(SleepVoice.time(input)==null) { input }
    fun parse(text: String)=SleepVoice.parse(text,fitting)
    check(parse("set sleep time to ten PM") == SleepCommand.Time(true,1320))
    check(parse("wake at seven AM.") == SleepCommand.Time(false,420))
    check(parse("set sleep time to ten") is SleepCommand.Invalid)
    check(parse("set sleep program to Sleep") == SleepCommand.Program(true,2))
    check(parse("set wake program to one") == SleepCommand.Program(false,1))
    check(parse("set wake program to TV!") == SleepCommand.Program(false,5))
    check(parse("set sleep program to Sleep or Universal") is SleepCommand.Invalid)
    check(parse("program Sleep")==null && parse("Sleep")==null)
    check(parse("configure sleep")==SleepCommand.Configure)
    check(parse("save sleep routine")==SleepCommand.Save)
    check(parse("enable sleep schedule")==SleepCommand.Enable)
    check(parse("sleep now")==SleepCommand.Now(true))
    check(parse("wake now")==SleepCommand.Now(false))
    check(parse("pause sleep routine")==SleepCommand.Override)
    check(parse("resume sleep routine")==SleepCommand.Resume)
    val asleep=SleepState().begin().completed(true,true)
    check(asleep.mode==SleepMode.ASLEEP && asleep.blocksNoise)
    check(asleep.manual().override && asleep.manual().resume().blocksNoise)
    val awake=asleep.begin().completed(false,true)
    check(awake.mode==SleepMode.AWAKE && !awake.blocksNoise)
    check(awake.begin().completed(true,false)==SleepState(SleepMode.UNKNOWN,true))
    check(asleep.begin().recovered()==SleepState(SleepMode.UNKNOWN,true))
    check(asleep.recovered()==asleep)
    fun delivery(due:Long=1000,now:Long=1000,enabled:Boolean=true,valid:Boolean=true,state:SleepState=awake)=sleepReminderDecision(due,now,enabled,valid,state)
    check(delivery()==SleepReminderDecision.DELIVER)
    check(delivery(now=999)==SleepReminderDecision.EARLY)
    check(delivery(now=901000)==SleepReminderDecision.DELIVER)
    check(delivery(now=901001)==SleepReminderDecision.MISSED)
    check(delivery(enabled=false)==SleepReminderDecision.DISABLED)
    check(delivery(valid=false)==SleepReminderDecision.INVALID)
    check(delivery(due=0)==SleepReminderDecision.INVALID)
    check(delivery(state=awake.manual())==SleepReminderDecision.PAUSED)
    check(delivery(state=awake.begin())==SleepReminderDecision.PAUSED)
    check(SleepRoutine.clock(1320)=="22:00")
    val zone=ZoneId.of("America/New_York")
    val spring=ZonedDateTime.of(2027,3,14,0,0,0,0,zone)
    check(SleepPreview.next(150,spring)!!.toLocalDate()==LocalDate.of(2027,3,15))
    val fall=ZonedDateTime.of(2026,11,1,0,0,0,0,zone)
    val first=SleepPreview.next(90,fall)!!
    check(first.offset==ZoneOffset.ofHours(-4))
    check(SleepPreview.next(90,first.plusMinutes(1))!!.toLocalDate()==LocalDate.of(2026,11,2))
    val now=ZonedDateTime.of(2026,10,17,23,0,0,0,zone)
    check(SleepPreview.next(1320,now)!!.toLocalDate()==LocalDate.of(2026,10,18))
    check(SleepPreview.next(420,now)!!.hour==7)
    check(SleepPreview.next(420,now.withZoneSameInstant(ZoneId.of("Europe/London")))!!.zone.id=="Europe/London")
    println("PASS: sleep routine validation, explicit-time parsing, program identity, next-day planning, timezone and DST skip/repeat guards")
}
